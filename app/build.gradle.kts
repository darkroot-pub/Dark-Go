android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.darkroot.darkgo"
    minSdk = 24
    targetSdk = 36
    versionCode = 1
    versionName = "1.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  signingConfigs {
    // NOTE: we deliberately do NOT declare a custom "debugConfig" signing config here.
    // AGP already provides a "debug" signing config backed by an auto-generated
    // ~/.android/debug.keystore -- no committed keystore file required, and it
    // just works in CI out of the box.
    create("release") {
      val keystorePathEnv = System.getenv("KEYSTORE_PATH")
      val storePasswordEnv = System.getenv("STORE_PASSWORD")
      val keyPasswordEnv = System.getenv("KEY_PASSWORD")
      if (keystorePathEnv != null && storePasswordEnv != null && keyPasswordEnv != null) {
        // Real release keystore, supplied via env vars (e.g. GitHub Actions secrets).
        storeFile = file(keystorePathEnv)
        storePassword = storePasswordEnv
        keyAlias = "upload"
        keyPassword = keyPasswordEnv
      } else {
        // No real release keystore configured yet -- fall back to the default debug
        // keystore so `assembleRelease`/`bundleRelease` still produce an installable
        // (though NOT Play-Store-ready) build without requiring any secrets.
        // Replace this branch's inputs with a real upload keystore before publishing.
        val debugSigning = signingConfigs.getByName("debug")
        storeFile = debugSigning.storeFile
        storePassword = debugSigning.storePassword
        keyAlias = debugSigning.keyAlias
        keyPassword = debugSigning.keyPassword
      }
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release")
    }
    debug {
      // Uses AGP's built-in "debug" signing config automatically.
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

